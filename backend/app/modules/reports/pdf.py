"""Branded, printable A4 PDFs for test reports and individual candidate results.

Documents are built exclusively from saved Assessify records. The result renderer intentionally never prints an
answer key, selected option text, or another student's data.
"""
from datetime import datetime, timezone

from fpdf import FPDF

from app.common.errors import ApiError
from app.modules.admit_cards.pdf import ACCENT, INK, LINE, MUTED, SOFT, _Doc
from app.modules.admit_cards.content import local, zone_label
from app.common.utils import utcnow


PAGE_WIDTH = 178  # A4 width less the shared 16 mm page margins


class _BrandedDoc(_Doc):
    def __init__(self, institution: str, title: str, subtitle: str, font_path: str = ""):
        super().__init__(font_path)
        self.institution = institution or "Institution"
        self.document_title = title
        self.subtitle = subtitle
        self.set_margins(16, 36, 16)
        self.set_auto_page_break(auto=True, margin=17)
        self.alias_nb_pages()

    def header(self):
        self.set_fill_color(*ACCENT)
        self.rect(0, 0, self.w, 29, style="F")
        self.set_xy(self.l_margin, 5)
        self.font(13, True, (255, 255, 255))
        self.cell(PAGE_WIDTH, 7, self.t(self.institution))
        self.set_xy(self.l_margin, 13)
        self.font(10, True, (255, 255, 255))
        self.cell(PAGE_WIDTH, 6, self.t(self.document_title))
        self.set_xy(self.l_margin, 20)
        self.font(8, False, (225, 228, 255))
        self.cell(PAGE_WIDTH, 5, self.t(self.subtitle[:170]))
        self.set_y(36)

    def footer(self):
        self.set_y(-12)
        self.set_draw_color(*LINE)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.set_y(-10)
        self.font(7.5, False, MUTED)
        self.cell(PAGE_WIDTH / 2, 5, self.t("Generated by Assessify"))
        self.cell(PAGE_WIDTH / 2, 5, self.t(f"Page {self.page_no()} of {{nb}}"), align="R")


def _safe(value) -> str:
    return "—" if value in (None, "") else str(value)


def _section(pdf: _BrandedDoc, title: str):
    _space(pdf, 11)
    pdf.font(9, True, ACCENT)
    pdf.cell(PAGE_WIDTH, 6, pdf.t(title.upper()), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(*LINE)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(2)


def _space(pdf: _BrandedDoc, height: float):
    if pdf.get_y() + height > pdf.page_break_trigger:
        pdf.add_page()


def _pair(pdf: _BrandedDoc, label: str, value, label_width: float = 42):
    text = _safe(value)
    pdf.font(8.5, True, MUTED)
    y = pdf.get_y()
    pdf.cell(label_width, 5.7, pdf.t(label))
    pdf.set_xy(pdf.l_margin + label_width, y)
    pdf.font(9, False, INK)
    pdf.multi_cell(PAGE_WIDTH - label_width, 5.7, pdf.t(text), new_x="LMARGIN", new_y="NEXT")


def _stat_cards(pdf: _BrandedDoc, values: list[tuple[str, str]]):
    gap = 3
    width = (PAGE_WIDTH - gap * (len(values) - 1)) / len(values)
    x0, y = pdf.l_margin, pdf.get_y()
    h = 18
    _space(pdf, h + 3)
    y = pdf.get_y()
    for i, (label, value) in enumerate(values):
        x = x0 + i * (width + gap)
        pdf.set_fill_color(*SOFT)
        pdf.set_draw_color(*LINE)
        pdf.rect(x, y, width, h, style="DF")
        pdf.set_xy(x + 2, y + 2)
        pdf.font(7.2, True, MUTED)
        pdf.cell(width - 4, 4, pdf.t(label.upper()))
        pdf.set_xy(x + 2, y + 7)
        pdf.font(12, True, ACCENT)
        pdf.cell(width - 4, 8, pdf.t(str(value)))
    pdf.set_y(y + h + 4)


def _wrap(pdf: _BrandedDoc, text: str, width: float, max_lines: int = 3) -> list[str]:
    """Small predictable wrapper for compact tabular rows."""
    words = str(text or "—").split()
    lines, current = [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if current and pdf.get_string_width(pdf.t(candidate)) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        while lines[-1] and pdf.get_string_width(pdf.t(lines[-1] + "…")) > width:
            lines[-1] = lines[-1][:-1]
        lines[-1] = lines[-1].rstrip() + "…"
    return lines or ["—"]


def _table(pdf: _BrandedDoc, headers: list[str], rows: list[list[str]], widths: list[float], *, font_size=7.6):
    def header_row():
        y = pdf.get_y()
        pdf.set_fill_color(*ACCENT)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font(pdf.family, "B", 7.4)
        x = pdf.l_margin
        for title, width in zip(headers, widths):
            pdf.set_xy(x, y)
            pdf.cell(width, 7, pdf.t(title), border=0, fill=True, align="L")
            x += width
        pdf.set_y(y + 7)

    header_row()
    for index, row in enumerate(rows):
        pdf.font(font_size, False, INK)
        wrapped = [_wrap(pdf, value, width - 3, max_lines=3) for value, width in zip(row, widths)]
        height = max(6, max(len(lines) for lines in wrapped) * 4 + 2)
        if pdf.get_y() + height > pdf.page_break_trigger:
            pdf.add_page()
            header_row()
        y, x = pdf.get_y(), pdf.l_margin
        if index % 2 == 0:
            pdf.set_fill_color(247, 248, 252)
            pdf.rect(pdf.l_margin, y, sum(widths), height, style="F")
        for lines, width in zip(wrapped, widths):
            pdf.set_xy(x + 1.5, y + 1)
            pdf.font(font_size, False, INK)
            pdf.multi_cell(width - 3, 4, pdf.t("\n".join(lines)), border=0, align="L")
            x += width
        pdf.set_y(y + height)
        pdf.set_draw_color(*LINE)
        pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())


def _local_stamp(value: datetime | None, tz_name: str) -> str:
    if value is None:
        return "—"
    return local(value, tz_name).strftime("%d %b %Y, %I:%M %p") + f" ({zone_label(tz_name, value)})"


def _format_iso_stamp(value: str | None, tz_name: str) -> str:
    """Format report API timestamps in the configured institution time zone."""
    if not value:
        return "—"
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        if parsed.tzinfo is not None:
            parsed = parsed.astimezone(timezone.utc).replace(tzinfo=None)
        return _local_stamp(parsed, tz_name)
    except (TypeError, ValueError):
        return str(value)


def _result_data(candidate, tz_name: str = "Asia/Karachi") -> dict:
    attempt = candidate.attempt
    if attempt is None or attempt.status != "submitted":
        raise ApiError("RESULT_NOT_READY", "A result PDF is available after the assessment has been submitted.", 409)

    items = list(attempt.items)
    correct = sum(1 for item in items if item.is_correct is True)
    answered = sum(1 for item in items if item.answer_index is not None)
    unanswered = max(0, len(items) - answered)
    incorrect = max(0, answered - correct)
    subject_rows: dict[str, dict] = {}
    for item in items:
        row = subject_rows.setdefault(item.subject_name, {"subject": item.subject_name, "questions": 0,
                                                          "correct": 0, "incorrect": 0, "unanswered": 0,
                                                          "score": 0, "max_score": 0})
        row["questions"] += 1
        row["max_score"] += item.marks
        if item.answer_index is None:
            row["unanswered"] += 1
        elif item.is_correct:
            row["correct"] += 1
            row["score"] += item.marks
        else:
            row["incorrect"] += 1
    subjects = list(subject_rows.values())
    for row in subjects:
        row["percent"] = round(100 * row["score"] / row["max_score"], 1) if row["max_score"] else 0

    test, inst = candidate.test, candidate.institution
    schedule = test.schedule
    percent = round(100 * (attempt.score or 0) / attempt.max_score, 1) if attempt.max_score else 0.0
    return {
        "institution": inst.display_name if inst else "Institution",
        "institution_name": inst.name if inst else "Institution",
        "test_name": test.name,
        "level": test.level,
        "exam_date": _local_stamp(schedule.starts_at if schedule else None, tz_name),
        "student_name": candidate.full_name,
        "student_id": candidate.roll_number,
        "department": candidate.department.name if candidate.department else "—",
        "email": candidate.email,
        "subject_names": ", ".join(dict.fromkeys(row["subject"] for row in subjects)) or "—",
        "attempt_reference": attempt.reference,
        "submitted_at": _local_stamp(attempt.submitted_at, tz_name),
        "generated_at": _local_stamp(utcnow(), tz_name),
        "score": int(attempt.score or 0),
        "max_score": int(attempt.max_score or 0),
        "percent": percent,
        "correct": correct,
        "incorrect": incorrect,
        "unanswered": unanswered,
        "questions": len(items),
        "subjects": subjects,
    }


def render_student_result(candidate, font_path: str = "", tz_name: str = "Asia/Karachi") -> bytes:
    data = _result_data(candidate, tz_name)
    pdf = _BrandedDoc(data["institution"], "STUDENT RESULT REPORT", data["test_name"], font_path)
    pdf.add_page()

    _section(pdf, "Student information")
    _pair(pdf, "Student name", data["student_name"])
    _pair(pdf, "Student ID / Roll number", data["student_id"])
    _pair(pdf, "Department", data["department"])
    _pair(pdf, "Course / Subject", data["subject_names"])
    if data["email"]:
        _pair(pdf, "Email", data["email"])

    _section(pdf, "Examination details")
    _pair(pdf, "Assessment", data["test_name"])
    _pair(pdf, "Degree level", data["level"])
    _pair(pdf, "Examination date", data["exam_date"])
    _pair(pdf, "Submitted", data["submitted_at"])
    _pair(pdf, "Result reference", data["attempt_reference"])

    _section(pdf, "Result summary")
    _stat_cards(pdf, [
        ("Obtained marks", f"{data['score']} / {data['max_score']}"),
        ("Percentage", f"{data['percent']}%"),
        ("Correct", str(data["correct"])),
        ("Incorrect", str(data["incorrect"])),
        ("Unanswered", str(data["unanswered"])),
    ])
    _pair(pdf, "Result status", "Submitted")

    if data["subjects"]:
        _section(pdf, "Subject-wise performance")
        _table(pdf, ["Subject", "Questions", "Correct", "Incorrect", "Unanswered", "Marks", "Score"],
               [[r["subject"], str(r["questions"]), str(r["correct"]), str(r["incorrect"]),
                 str(r["unanswered"]), str(r["max_score"]), f"{r['score']} ({r['percent']}%)"]
                for r in data["subjects"]], [49, 19, 18, 20, 23, 18, 31], font_size=7.1)

    _section(pdf, "Document information")
    _pair(pdf, "Generated", data["generated_at"])
    pdf.font(8, False, MUTED)
    pdf.multi_cell(PAGE_WIDTH, 4.5, pdf.t("This document reflects the submitted result stored in Assessify. It does not include question text, correct answers, answer keys, or other students' information."))
    return bytes(pdf.output())


def render_test_report(report: dict, institution, font_path: str = "", tz_name: str = "Asia/Karachi") -> bytes:
    inst_name = institution.display_name if institution else "Institution"
    test = report["test"]
    pdf = _BrandedDoc(inst_name, "ASSESSMENT REPORT", test["name"], font_path)
    pdf.add_page()

    _section(pdf, "Assessment information")
    _pair(pdf, "Assessment", test["name"])
    _pair(pdf, "Institution", inst_name)
    _pair(pdf, "Degree level", test["level"])
    _pair(pdf, "Start", _format_iso_stamp(test["starts_at"], tz_name))
    _pair(pdf, "End", _format_iso_stamp(test["ends_at"], tz_name))
    _pair(pdf, "Report generated", _local_stamp(utcnow(), tz_name))

    summary = report["summary"]
    _section(pdf, "Performance overview")
    _stat_cards(pdf, [
        ("Candidates", str(summary["candidates"])),
        ("Submitted", str(summary["submitted"])),
        ("Average", _safe(summary["average_percent"]) + ("%" if summary["average_percent"] is not None else "")),
        ("Highest", _safe(summary["highest_percent"]) + ("%" if summary["highest_percent"] is not None else "")),
    ])
    _pair(pdf, "Median score", f"{summary['median_percent']}%" if summary["median_percent"] is not None else "—")
    _pair(pdf, "Lowest score", f"{summary['lowest_percent']}%" if summary["lowest_percent"] is not None else "—")
    _pair(pdf, "Still taking it", summary["in_progress"])
    _pair(pdf, "Not attempted", summary["not_attempted"])
    _pair(pdf, "Auto-submitted", summary["auto_submitted"])

    if report.get("by_department"):
        _section(pdf, "Performance by department")
        _table(pdf, ["Department", "Candidates", "Submitted", "Average", "Highest"],
               [[x["name"], str(x["candidates"]), str(x["submitted"]),
                 f"{x['average_percent']}%" if x["average_percent"] is not None else "—",
                 f"{x['highest_percent']}%" if x["highest_percent"] is not None else "—"]
                for x in report["by_department"]], [72, 24, 24, 29, 29])

    if report.get("by_subject"):
        _section(pdf, "Subject-wise performance")
        _table(pdf, ["Subject", "Questions", "Correct", "Unanswered", "Accuracy"],
               [[x["subject"], str(x["questions"]), str(x["correct"]), str(x["unanswered"]),
                 f"{x['accuracy_percent']}%" if x["accuracy_percent"] is not None else "—"]
                for x in report["by_subject"]], [64, 25, 25, 31, 33])

    _section(pdf, "Candidate results")
    rows = []
    for row in report["candidates"]:
        score = f"{row['score']} / {row['max_score']}" if row["score"] is not None else "—"
        percent = f"{row['percent']}%" if row["percent"] is not None else "—"
        rows.append([str(row["rank"] or "—"), row["full_name"], row["roll_number"] or "—",
                     row["department"]["name"], row["status"].replace("_", " ").title(), score, percent])
    if rows:
        _table(pdf, ["Rank", "Student", "Student ID", "Department", "Status", "Score", "%"],
               rows, [10, 38, 24, 38, 23, 28, 17], font_size=7.1)
    else:
        pdf.font(9, False, MUTED)
        pdf.cell(PAGE_WIDTH, 7, pdf.t("No candidates match the selected report filters."), new_x="LMARGIN", new_y="NEXT")

    pdf.ln(2)
    pdf.font(7.8, False, MUTED)
    pdf.multi_cell(PAGE_WIDTH, 4.2, pdf.t("This report contains assessment statistics and candidate scores from saved Assessify records. It does not contain question text or answer keys."))
    return bytes(pdf.output())
